export function drawDevGlyph(glyphEntry: DevGlyphEntry, parent: SVGElement, extraOffsets?: { y?: number, x?: number }) {
  const newPath = document.createElementNS(SVG_HREF, "path");
  newPath.setAttribute("d", glyphEntry.path);

  let totalXOffset = extraOffsets?.x ?? 0;
  let totalYOffset = glyphEntry.yOffset + (extraOffsets?.y ?? 0);

  if (totalYOffset !== 0 || totalXOffset !== 0) {
    newPath.setAttribute("transform", `translate(${totalXOffset}, ${totalYOffset})`);
  }

  parent.appendChild(newPath);
}